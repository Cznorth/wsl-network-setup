# Runs a second sshd as the current user inside the interactive desktop session (Session 1).
# The system sshd service runs as LocalSystem, so its children land in Session 0 with an S4U token
# (no GUI, no Credential Manager / DPAPI). This instance is started by a logon-triggered,
# interactive scheduled task, so everything it spawns lives in the user's real logon session.
# Only the user that runs it can log in. Needs admin once (RunLevel Highest).
# NOTE: keep this file ASCII-only; Windows PowerShell 5.1 reads BOM-less files as ANSI.
param([int]$Port = 2223, [string]$Listen = '127.0.0.1', [string]$Name = 'wslproxy-usersshd', [switch]$Uninstall)
$ErrorActionPreference = 'Stop'
$dir  = Join-Path $env:USERPROFILE '.ssh\usersshd'
$sshd = "$env:SystemRoot\System32\OpenSSH\sshd.exe"

Stop-ScheduledTask -TaskName $Name -ErrorAction SilentlyContinue
$pidFile = Join-Path $dir 'sshd.pid'
if (Test-Path $pidFile) { Stop-Process -Id ([int](Get-Content $pidFile)) -Force -ErrorAction SilentlyContinue }
if ($Uninstall) {
    Unregister-ScheduledTask -TaskName $Name -Confirm:$false -ErrorAction SilentlyContinue
    'uninstalled'; return
}

New-Item -ItemType Directory -Force $dir | Out-Null
$key = Join-Path $dir 'ssh_host_ed25519_key'
if (-not (Test-Path $key)) { & ssh-keygen.exe -q -t ed25519 -N '""' -f $key }
& icacls.exe $key /inheritance:r /grant:r "${env:USERNAME}:F" | Out-Null
$fwd = $dir -replace '\\', '/'
@"
# Generated by install-usersshd.ps1 - sshd running as $env:USERNAME in the interactive session
Port $Port
ListenAddress $Listen
HostKey $fwd/ssh_host_ed25519_key
PidFile $fwd/sshd.pid
AuthorizedKeysFile .ssh/authorized_keys
PubkeyAuthentication yes
PasswordAuthentication no
KbdInteractiveAuthentication no
AllowTcpForwarding yes
Subsystem sftp sftp-server.exe
"@ | Set-Content -Encoding ascii (Join-Path $dir 'sshd_config')
& $sshd -t -f (Join-Path $dir 'sshd_config'); if ($LASTEXITCODE) { throw 'sshd config test failed' }

# conhost --headless: no console window on the desktop; pty sessions still get their own ConPTY.
$a = New-ScheduledTaskAction -Execute "$env:SystemRoot\System32\conhost.exe" `
     -Argument "--headless `"$sshd`" -D -f `"$dir\sshd_config`" -E `"$dir\sshd.log`""
$t = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
$p = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Highest
$s = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -StartWhenAvailable `
     -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1) `
     -MultipleInstances IgnoreNew
Register-ScheduledTask -TaskName $Name -Action $a -Trigger $t -Principal $p -Settings $s -Force | Out-Null
Start-ScheduledTask -TaskName $Name
Start-Sleep 2
(Get-ScheduledTask $Name).State
